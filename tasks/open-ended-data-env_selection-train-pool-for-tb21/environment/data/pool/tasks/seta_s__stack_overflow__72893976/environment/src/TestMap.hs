  , worldPlayerLoc = "R1"
  , worldFlags     = Set.fromList [GameFlag "game_started"]
  }

testInventoryOps :: IO ()
testInventoryOps = do
  let dm0 = DualMap.empty
      dm1 = DualMap.insert ("book" :: Text) ("R3" :: Text) dm0
      dm2 = DualMap.insert "key" "R4" dm1
      dm3 = DualMap.insert "knife" "R5" dm2
  TIO.putStrLn "=== Inventory Test ==="
  TIO.putStrLn $ T.concat ["Initial items: ", T.pack (show (DualMap.size dm3))]

  -- Move book from R3 to player (represented by "PLAYER")
  let dm4 = DualMap.insert "book" "PLAYER" dm3
  TIO.putStrLn $ T.concat ["After pickup book: ", T.pack (show (DualMap.toList dm4))]
  TIO.putStrLn $ T.concat ["Book location: ", T.pack (show (DualMap.lookupLeft "book" dm4))]

  -- Drop book into R1
  let dm5 = DualMap.insert "book" "R1" dm4
  TIO.putStrLn $ T.concat ["After drop book to R1: ", T.pack (show (DualMap.toList dm5))]

  -- Transfer key from R4 to same location as book (R1)
  -- This should NOT cause duplication — each item has exactly one location
  let dm6 = DualMap.insert "key" "R1" dm5
  TIO.putStrLn $ T.concat ["After move key to R1: ", T.pack (show (DualMap.toList dm6))]
  TIO.putStrLn $ T.concat ["Items at R1: book=", T.pack (show (DualMap.lookupLeft "book" dm6))
                           , " key=", T.pack (show (DualMap.lookupLeft "key" dm6))]

  -- Check no orphaned reverse entries
  let totalItems = DualMap.size dm6
  TIO.putStrLn $ T.concat ["Total items: ", T.pack (show totalItems)]
  TIO.putStrLn $ T.concat ["R4 occupant: ", T.pack (show (DualMap.lookupRight "R4" dm6))]
  TIO.putStrLn "=== Inventory Test Complete ==="

testSaveLoad :: IO ()
testSaveLoad = do
  let w = testWorld
  TIO.putStrLn "=== Save/Load Test ==="
  saveWorld "/tmp/save.json" w
  result <- loadWorld "/tmp/save.json"
  case result of
    Left err -> TIO.putStrLn $ T.concat ["Load failed: ", T.pack err]
    Right w' -> do
      TIO.putStrLn $ T.concat ["Edge count original: ", T.pack (show (length (worldEdges w)))]
      TIO.putStrLn $ T.concat ["Edge count loaded:   ", T.pack (show (length (worldEdges w')))]
      TIO.putStrLn $ T.concat ["Player loc match: ", T.pack (show (worldPlayerLoc w == worldPlayerLoc w'))]
      TIO.putStrLn $ T.concat ["Inventory match: ", T.pack (show (worldInventory w == worldInventory w'))]
      TIO.putStrLn $ T.concat ["Flags match: ", T.pack (show (worldFlags w == worldFlags w'))]
      TIO.putStrLn $ T.concat ["Edges match: ", T.pack (show (worldEdges w == worldEdges w'))]
      TIO.putStrLn $ T.concat ["Rooms match: ", T.pack (show (worldRooms w == worldRooms w'))]
      TIO.putStrLn $ T.concat ["World match: ", T.pack (show (w == w'))]
  TIO.putStrLn "=== Save/Load Test Complete ==="
