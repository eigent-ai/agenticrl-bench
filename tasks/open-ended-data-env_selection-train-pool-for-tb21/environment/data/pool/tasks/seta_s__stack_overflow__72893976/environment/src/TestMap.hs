testWorld :: GameWorld
testWorld = GameWorld
  { worldRooms     = testRooms
  , worldEdges     = allEdges buildTestGraph
  , worldInventory = Map.fromList
      [ ("book", "R3"), ("key", "R4"), ("knife", "R5")
      , ("lantern", "R6"), ("gem", "R7")
