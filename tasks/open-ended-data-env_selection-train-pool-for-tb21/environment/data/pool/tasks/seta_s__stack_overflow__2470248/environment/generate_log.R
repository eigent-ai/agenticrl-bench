survey <- read.csv("data/survey.csv", sep=";", stringsAsFactors=FALSE)
fc <- file("output/pipeline.log", "w")
writeLines(paste0("[", Sys.time(), "] Pipeline started"), fc)
writeLines(paste0("[", Sys.time(), "] Loaded ", nrow(survey), " survey rows"), fc)
n_cats <- length(unique(survey$category))
writeLines(paste0("[", Sys.time(), "] Found ", n_cats, " categories"), fc)
writeLines(paste0("[", Sys.time(), "] Processing complete, total records: ", nrow(survey)), fc)
writeLines(n_cats, fc)
writeLines(paste0("[", Sys.time(), "] Pipeline complete"), fc)
cat("Log generated\n")
