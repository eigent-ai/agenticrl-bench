package pipeline

import java.io.{FileWriter, PrintWriter}

object LogWriter {

  def writeSummarySection(logFile: String, content: String): Unit = {
    val writer = new PrintWriter(new FileWriter(logFile))
    try {
      writer.println(content)
    } finally {
      writer.close()
    }
  }

  def generateHeader(sensors: Seq[SensorReading]): String = {
    s"""=== HEADER ===
       |Sensor Pipeline Report
       |Total sensors: ${sensors.size}
       |Generated by: SensorPipeline v1.0
       |=== END HEADER ===""".stripMargin
  }

  def generateStatistics(sensors: Seq[SensorReading]): String = {
    val values = sensors.map(_.value)
    val mean = if (values.nonEmpty) values.sum / values.size else 0.0
    s"""=== STATISTICS ===
       |Min value: ${values.min}
       |Max value: ${values.max}
       |Mean value: $mean
       |Readings above threshold (50.0): ${sensors.count(_.value > 50.0)}
       |=== END STATISTICS ===""".stripMargin
  }

  def generateWarnings(sensors: Seq[SensorReading]): String = {
    val highReadings = sensors.filter(_.value > 90.0)
    val warnings = if (highReadings.nonEmpty) {
      highReadings.map(s => s"  WARNING: ${s.name} at ${s.location} = ${s.value}").mkString("\n")
    } else {
      "  No high-value readings detected."
    }
    s"""=== WARNINGS ===
       |High-value sensors (>90.0):
       |$warnings
       |=== END WARNINGS ===""".stripMargin
  }

  def generateFooter(sensors: Seq[SensorReading]): String = {
    s"""=== FOOTER ===
       |Processing complete.
       |Total records processed: ${sensors.size}
       |=== END FOOTER ===""".stripMargin
  }
}
