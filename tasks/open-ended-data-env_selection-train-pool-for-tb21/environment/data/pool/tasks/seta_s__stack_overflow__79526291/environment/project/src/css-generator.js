export class CssGenerator {
  constructor(themeParser) {
    this.themeParser = themeParser;
  }

  generateElementStyle(element) {
    const lines = [];
    lines.push(`${element.selector} {`);

    if (element.resolvedColor) {
      lines.push(`  color: ${element.resolvedColor};`);
    }
    if (element.resolvedBackground) {
      lines.push(`  background-color: ${element.resolvedBackground};`);
    }
    if (element.fontSize) {
      lines.push(`  font-size: ${element.fontSize};`);
    }
    if (element.fontWeight) {
      lines.push(`  font-weight: ${element.fontWeight};`);
    }

    lines.push('}');
    return lines.join('\n');
  }

  generatePlaceholderStyles(element) {
    if (!element.placeholder) return '';

    const color = element.resolvedColor || '#999';
    const lines = [];

    lines.push(`${element.selector}::-webkit-placeholder {`);
    lines.push(`  color: ${color};`);
    lines.push(`  opacity: 0.7;`);
    lines.push('}');
    lines.push('');
    lines.push(`${element.selector}::-moz-placeholder {`);
    lines.push(`  color: ${color};`);
    lines.push(`  opacity: 0.7;`);
    lines.push('}');
    lines.push('');
    lines.push(`${element.selector}:-ms-input-placeholder {`);
    lines.push(`  color: ${color};`);
    lines.push(`  opacity: 0.7;`);
    lines.push('}');
    lines.push('');
    lines.push(`${element.selector}::placeholder {`);
    lines.push(`  color: ${color};`);
    lines.push(`  opacity: 0.7;`);
    lines.push('}');

    return lines.join('\n');
  }

  generateButtonStyles(element) {
    if (element.type === 'navigation') return '';

    const lines = [];

    if (element.hover) {
      const hoverBg = element.hover.resolvedBackground || element.resolvedBackground;
      const hoverColor = element.hover.resolvedColor || element.resolvedColor;
      lines.push(`${element.selector}:hover {`);
      lines.push(`  background-color: ${hoverBg};`);
      lines.push(`  color: ${hoverColor};`);
      lines.push(`  cursor: pointer;`);
      lines.push(`  text-decoration: none;`);
      lines.push('}');
      lines.push('');
    }

    if (element.active) {
      const activeBg = element.active.resolvedBackground || element.resolvedBackground;
      const activeColor = element.active.resolvedColor || element.resolvedColor;
      lines.push(`${element.selector}:active {`);
      lines.push(`  background-color: ${activeBg};`);
      lines.push(`  color: ${activeColor};`);
      lines.push('}');
    }

    return lines.join('\n');
  }

  generate() {
    const elements = this.themeParser.getResolvedHudElements();
    const sections = [];

    sections.push('/* HUD Overlay Styles */');
    sections.push('/* Generated by tilemap-pipeline */');
    sections.push('');

    for (const element of elements) {
      sections.push(this.generateElementStyle(element));
      sections.push('');

      if (element.placeholder) {
        sections.push(this.generatePlaceholderStyles(element));
        sections.push('');
      }

      if (element.hover || element.active) {
        const btnStyles = this.generateButtonStyles(element);
        if (btnStyles) {
          sections.push(btnStyles);
          sections.push('');
        }
      }
    }

    return sections.join('\n');
  }
}
